// 1. var, let, and const
// Interview Question
// What is the difference between var, let, and const?
// 🇧🇩 বাংলা
// var, let, এবং const দি য়ে variable declare করা হয়।
// ● var → function scoped
// ● let → block scoped এবং reassign করা যায়
// ● const → block scoped এবং reassign করা যায় না
// ● var একই scope-এ redeclare করা যায়
// ● let ও const একই scope-এ redeclare করা যায় না
// var a = 10;
// let b = 20;
// const c = 30;
// Modern JavaScript-এ সাধারণত let এবং const ব্যবহার করা হয়।
// 🇬🇧 English
// var, let, and const are used to declare variables.
// ● var is function-scoped.
// ● let is block-scoped and can be reassigned.
// ● const is block-scoped and cannot be reassigned.
// ● var can be redeclared in the same scope.
// ● let and const cannot be redeclared in the same scope.
